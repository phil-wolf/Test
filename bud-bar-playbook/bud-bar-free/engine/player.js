/* =====================================================================
   Course player
   Reads window.COURSE_DATA (generated by build.py from /content) and
   handles navigation, bookmarking, resume, quiz scoring, the calculator,
   and reporting to the LMS via window.SCORM.
   You should not need to edit this file to change course wording.
   ===================================================================== */
(function () {
  'use strict';

  var C = window.COURSE_DATA;
  var S = window.SCORM;
  var $ = function (id) { return document.getElementById(id); };

  /* Flatten modules into a list of screens */
  var screens = [];
  C.modules.forEach(function (m, mi) {
    m.screens.forEach(function (s, si) {
      screens.push({
        module: mi, firstOfModule: si === 0, titleHtml: s.title_html, blocks: s.blocks,
        gated: s.blocks.some(function (b) { return b.embed === 'quiz'; })
      });
    });
  });
  var LAST = screens.length - 1;

  /* Learner state. Saved to cmi.suspend_data as compact JSON. */
  var st = { i: 0, max: 0, quiz: { a: [], s: null, n: 0 }, calc: null };
  var status = 'incomplete';
  var startedAt = Date.now();
  var saveTimer = null;

  /* ---------------- LMS ---------------- */
  function startLms() {
    S.init(C.id);
    status = S.get('cmi.core.lesson_status');
    if (!status || status === 'not attempted') {
      status = 'incomplete';
      S.set('cmi.core.lesson_status', status);
    }
    var raw = S.get('cmi.suspend_data');
    if (raw) {
      try {
        var d = JSON.parse(raw);
        if (d && d.v === 1) {
          st.max = d.m | 0;
          if (d.q) st.quiz = { a: d.q.a || [], s: d.q.s == null ? null : d.q.s, n: d.q.n | 0 };
          st.calc = d.c || null;
        }
      } catch (e) { /* ignore bad data from an older version */ }
    }
    var loc = parseInt(S.get('cmi.core.lesson_location'), 10);
    var resumed = false;
    if (loc > 0 && loc <= LAST) { st.i = loc; resumed = true; }
    st.max = Math.min(Math.max(st.max, st.i), LAST);
    return resumed;
  }

  function save() {
    clearTimeout(saveTimer);
    S.set('cmi.core.lesson_location', String(st.i));
    S.set('cmi.suspend_data', JSON.stringify({ v: 1, m: st.max, q: st.quiz, c: st.calc }));
    S.commit();
  }
  function saveSoon() { clearTimeout(saveTimer); saveTimer = setTimeout(save, 800); }

  function setStatus(s) {
    status = s;
    S.set('cmi.core.lesson_status', s);
  }

  var exited = false;
  function exitCourse() {
    if (exited || window.__skipExit) return;
    exited = true;
    save();
    S.set('cmi.core.session_time', S.formatTime(Date.now() - startedAt));
    // "suspend" tells the LMS to keep the bookmark for next time.
    var done = status === 'passed' || status === 'completed';
    S.set('cmi.core.exit', done ? '' : 'suspend');
    S.commit();
    S.finish();
    var nav = document.querySelectorAll('.navbar button, #screen button, #screen input');
    Array.prototype.forEach.call(nav, function (b) { b.disabled = true; });
    showBanner('Your progress has been saved. You can close this window.', false);
  }
  window.addEventListener('pagehide', exitCourse);
  window.addEventListener('beforeunload', exitCourse);
  window.addEventListener('course:exit', exitCourse);

  /* ---------------- Rendering ---------------- */
  function el(tag, cls, html) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (html != null) e.innerHTML = html;
    return e;
  }

  function render(moveFocus) {
    var s = screens[st.i];
    var mod = C.modules[s.module];
    var art = $('screen');
    art.innerHTML = '';
    var eyebrow = el('p', 'eyebrow');
    eyebrow.textContent = 'Module ' + (s.module + 1) + ' of ' + C.modules.length + ' · ' + mod.title;
    var h1 = el('h1', null, s.titleHtml);
    h1.id = 'screen-title';
    h1.tabIndex = -1;
    art.append(eyebrow, h1);

    s.blocks.forEach(function (b) {
      var box = el('div', 'block');
      if (b.embed) EMBEDS[b.embed](box, b.data);
      else box.innerHTML = b.html;
      art.appendChild(box);
    });

    if (st.i === LAST) {
      var v = el('p', 'version');
      v.textContent = C.title + ' · Version ' + C.version + ' · Built ' + C.built;
      art.appendChild(v);
      if (C.completion === 'end' && status !== 'completed') setStatus('completed');
    }

    if (st.i > st.max) st.max = st.i;
    updateChrome();
    save();
    window.scrollTo(0, 0);
    if (moveFocus) h1.focus();
  }

  function updateChrome() {
    var s = screens[st.i];
    $('counter').textContent = 'Screen ' + (st.i + 1) + ' of ' + screens.length;
    $('progress-bar').style.width = Math.round(((st.i + 1) / screens.length) * 100) + '%';
    $('progress').setAttribute('aria-valuenow', String(st.i + 1));
    $('prev').disabled = st.i === 0;
    var next = $('next');
    var blocked = s.gated && st.quiz.s === null;
    next.hidden = st.i === LAST;
    next.disabled = blocked;
    $('next-hint').textContent = blocked ? 'Submit your answers to continue.' : '';
    renderMenu();
  }

  function renderMenu() {
    var list = $('menu-list');
    list.innerHTML = '';
    var cur = screens[st.i].module;
    C.modules.forEach(function (m, mi) {
      var firstIdx = screens.findIndex(function (s) { return s.module === mi; });
      var li = el('li');
      var b = el('button', 'menu-item');
      b.type = 'button';
      b.textContent = (mi + 1) + '. ' + m.title;
      if (mi === cur) b.setAttribute('aria-current', 'step');
      if (firstIdx > st.max) { b.disabled = true; b.title = 'Not reached yet'; }
      b.addEventListener('click', function () { go(firstIdx); closeMenuIfOverlay(); });
      li.appendChild(b);
      list.appendChild(li);
    });
  }

  function go(i) {
    if (i < 0 || i > LAST || exited) return;
    st.i = i;
    render(true);
  }

  function showBanner(text, withRestart) {
    var b = $('banner');
    b.innerHTML = '';
    b.hidden = false;
    var p = el('p');
    p.textContent = text;
    b.appendChild(p);
    if (withRestart) {
      var r = el('button', 'btn btn-secondary btn-small');
      r.type = 'button';
      r.textContent = 'Go to the first screen';
      r.addEventListener('click', function () { b.hidden = true; go(0); });
      b.appendChild(r);
    }
  }

  /* ---------------- Menu ---------------- */
  var wide = window.matchMedia('(min-width: 900px)');
  function setMenu(open) {
    $('menu').hidden = !open;
    $('menu-btn').setAttribute('aria-expanded', String(open));
    document.body.classList.toggle('menu-open', open && !wide.matches);
  }
  function closeMenuIfOverlay() { if (!wide.matches) setMenu(false); }

  /* ---------------- Embeds ---------------- */
  var EMBEDS = { quiz: renderQuiz, calculator: renderCalculator };

  function renderQuiz(box, data) {
    var qs = data.questions;
    var form = el('form', 'quiz');
    form.noValidate = true;
    var answered = st.quiz.s !== null;

    qs.forEach(function (q, qi) {
      var fs = el('fieldset', 'q');
      var lg = el('legend', null, '<span class="qnum">Question ' + (qi + 1) + ' of ' + qs.length + '</span> ' + q.q_html);
      fs.appendChild(lg);
      q.options_html.forEach(function (o, oi) {
        var id = 'q' + qi + 'o' + oi;
        var lab = el('label', 'opt');
        lab.htmlFor = id;
        var inp = el('input');
        inp.type = 'radio'; inp.name = 'q' + qi; inp.id = id; inp.value = String(oi);
        if (answered && st.quiz.a[qi] === oi) inp.checked = true;
        lab.append(inp, el('span', null, o));
        fs.appendChild(lab);
      });
      var fb = el('p', 'feedback');
      fb.hidden = true;
      fs.appendChild(fb);
      form.appendChild(fs);
    });

    var result = el('div', 'quiz-result');
    result.setAttribute('role', 'status');
    result.setAttribute('aria-live', 'polite');
    var actions = el('div', 'quiz-actions');
    var submit = el('button', 'btn btn-primary');
    submit.type = 'submit';
    submit.textContent = 'Submit answers';
    var retry = el('button', 'btn btn-secondary');
    retry.type = 'button';
    retry.textContent = 'Try again';
    retry.hidden = true;
    actions.append(submit, retry);
    form.append(actions, result);
    box.appendChild(form);

    var pass = C.passing_score || 100;

    function showResults() {
      var correct = 0;
      qs.forEach(function (q, qi) {
        var fs = form.children[qi];
        var ok = st.quiz.a[qi] === q.answer;
        if (ok) correct++;
        fs.classList.add(ok ? 'is-correct' : 'is-wrong');
        var fb = fs.querySelector('.feedback');
        fb.hidden = false;
        fb.innerHTML = '<strong>' + (ok ? 'Correct.' : 'Not quite.') + '</strong> ' + q.feedback_html;
        Array.prototype.forEach.call(fs.querySelectorAll('input'), function (i) { i.disabled = true; });
      });
      submit.hidden = true;
      var pct = st.quiz.s;
      var msg = 'You scored ' + pct + '% (' + correct + ' of ' + qs.length + ' correct). ';
      if (C.completion === 'quiz') {
        msg += pct >= pass ? 'You passed. The passing score is ' + pass + '%.'
                           : 'The passing score is ' + pass + '%. Review the feedback, then try again.';
      }
      result.className = 'quiz-result ' + (pct >= pass ? 'good' : 'bad');
      result.textContent = msg;
      retry.hidden = !(pct < pass && status !== 'passed');
    }

    form.addEventListener('submit', function (e) {
      e.preventDefault();
      var answers = qs.map(function (q, qi) {
        var c = form.querySelector('input[name="q' + qi + '"]:checked');
        return c ? parseInt(c.value, 10) : -1;
      });
      var missing = answers.indexOf(-1);
      if (missing >= 0) {
        result.className = 'quiz-result bad';
        result.textContent = 'Please answer every question. Question ' + (missing + 1) + ' has no answer yet.';
        form.querySelector('input[name="q' + missing + '"]').focus();
        return;
      }
      var correct = answers.filter(function (a, i) { return a === qs[i].answer; }).length;
      var pct = Math.round((correct / qs.length) * 100);
      st.quiz = { a: answers, s: pct, n: st.quiz.n + 1 };
      S.set('cmi.core.score.min', '0');
      S.set('cmi.core.score.max', '100');
      S.set('cmi.core.score.raw', String(pct));
      if (C.completion === 'quiz' && status !== 'passed') setStatus(pct >= pass ? 'passed' : 'failed');
      save();
      showResults();
      updateChrome();
      result.focus();
    });

    retry.addEventListener('click', function () {
      st.quiz = { a: [], s: null, n: st.quiz.n };
      save();
      render(true);
    });

    result.tabIndex = -1;
    if (answered) showResults();
  }

  function money(n) {
    var r = Math.round(n);
    return (r < 0 ? '−$' : '$') + Math.abs(r).toLocaleString('en-US');
  }

  function renderCalculator(box, data) {
    var vals = {};
    data.inputs.forEach(function (f) { vals[f.id] = f.default; });
    var startup = data.startup_costs.map(function (c) { return c.default; });
    if (st.calc) {
      if (st.calc.v) Object.keys(vals).forEach(function (k) { if (typeof st.calc.v[k] === 'number') vals[k] = st.calc.v[k]; });
      if (Array.isArray(st.calc.s) && st.calc.s.length === startup.length) startup = st.calc.s.slice();
    }

    var wrap = el('div', 'calc');
    wrap.appendChild(el('p', 'calc-note', data.note_html));

    function field(id, labelHtml, value, isMoney, step, onChange) {
      var f = el('div', 'calc-field');
      var lab = el('label', null, labelHtml);
      lab.htmlFor = id;
      var row = el('div', 'calc-input' + (isMoney ? ' money' : ''));
      var inp = el('input');
      inp.type = 'number'; inp.id = id; inp.min = '0'; inp.step = String(step || 1);
      inp.inputMode = 'decimal';
      inp.value = String(value);
      inp.addEventListener('input', function () {
        var n = parseFloat(inp.value);
        onChange(isFinite(n) && n >= 0 ? n : 0);
      });
      row.appendChild(inp);
      f.append(lab, row);
      return f;
    }

    var ev = el('fieldset', 'calc-set');
    ev.appendChild(el('legend', null, data.event_heading_html));
    var grid = el('div', 'calc-grid');
    data.inputs.forEach(function (f) {
      grid.appendChild(field('calc-' + f.id, f.label_html, vals[f.id], f.money, f.step, function (n) { vals[f.id] = n; update(); }));
    });
    ev.appendChild(grid);
    wrap.appendChild(ev);

    var out = el('div', 'calc-out');
    wrap.appendChild(out);

    var su = el('fieldset', 'calc-set');
    su.appendChild(el('legend', null, data.startup_heading_html));
    var sgrid = el('div', 'calc-grid');
    data.startup_costs.forEach(function (c, ci) {
      sgrid.appendChild(field('calc-su-' + ci, c.label_html, startup[ci], true, 50, function (n) { startup[ci] = n; update(); }));
    });
    su.appendChild(sgrid);
    wrap.appendChild(su);

    var sout = el('div', 'calc-out');
    wrap.appendChild(sout);

    var reset = el('button', 'btn btn-secondary btn-small');
    reset.type = 'button';
    reset.textContent = 'Reset to example assumptions';
    reset.addEventListener('click', function () { st.calc = null; save(); render(false); });
    wrap.appendChild(reset);
    box.appendChild(wrap);

    function update() {
      var v = vals;
      var revenue = v.hourly_rate * v.hours + v.per_guest_fee * v.guests;
      var labor = v.staff * v.staff_pay * (v.hours + v.setup_hours);
      var supplies = v.supplies_per_guest * v.guests;
      var other = v.other_costs;
      var costs = labor + supplies + other;
      var profit = revenue - costs;
      out.innerHTML =
        '<table class="calc-table"><caption>One event</caption><tbody>' +
        '<tr><th scope="row">Revenue (rate × hours + per-guest fee × guests)</th><td>' + money(revenue) + '</td></tr>' +
        '<tr><th scope="row">Staff pay (staff × pay × (service + setup hours))</th><td>− ' + money(labor) + '</td></tr>' +
        '<tr><th scope="row">Supplies (per guest × guests)</th><td>− ' + money(supplies) + '</td></tr>' +
        '<tr><th scope="row">Other event costs</th><td>− ' + money(other) + '</td></tr>' +
        '<tr class="total"><th scope="row">Profit per event</th><td><output id="calc-profit">' + money(profit) + '</output></td></tr>' +
        '</tbody></table>';
      var total = startup.reduce(function (a, b) { return a + b; }, 0);
      var events = profit > 0 ? Math.ceil(total / profit) : null;
      sout.innerHTML =
        '<p class="calc-summary" aria-live="polite">Startup total: <strong>' + money(total) + '</strong>. ' +
        (events ? 'At this profit per event, you would earn back your startup costs after about <strong>' + events + ' event' + (events === 1 ? '' : 's') + '</strong>.'
                : 'This event loses money, so it never pays back the startup costs. Raise your rates or cut costs.') +
        '</p>';
      st.calc = { v: Object.assign({}, vals), s: startup.slice() };
      saveSoon();
    }
    update();
  }

  /* ---------------- Start ---------------- */
  document.addEventListener('DOMContentLoaded', function () {
    document.title = C.title;
    $('progress').setAttribute('aria-valuemax', String(screens.length));
    var resumed = startLms();
    if (window.DebugPanel) window.DebugPanel.start();

    $('prev').addEventListener('click', function () { go(st.i - 1); });
    $('next').addEventListener('click', function () { go(st.i + 1); });
    $('menu-btn').addEventListener('click', function () { setMenu($('menu').hidden); });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && !$('menu').hidden && !wide.matches) { setMenu(false); $('menu-btn').focus(); }
    });
    setMenu(wide.matches);
    wide.addEventListener('change', function () { setMenu(wide.matches); });

    if (resumed) showBanner('Welcome back. You are picking up where you left off.', true);
    render(false);
  });
})();
